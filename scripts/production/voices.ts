/**
 * Audio Director — voice generation.  Uses the locally installed espeak-ng (free, offline) as SYNTHETIC TTS PLACEHOLDER.
 * It is NOT a voice performance: robotic, limited Korean prosody. Real recordings replace files in public/voices/<dialogueId>.wav.
 * Lip-sync cues are derived from the real waveform envelope (open/close) + Hangul vowel shapes from the text.
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { loadShots, dialogueId, writeJsonAtomic } from './common';
import { textMouthCues, MouthShape } from '../../src/animation/Face';

const VOICES: Record<string, { v: string; p: number; s: number; a: number }> = {
  soma: { v: 'ko+m3', p: 58, s: 158, a: 160 }, veyra: { v: 'ko+m7', p: 28, s: 140, a: 175 }, mio: { v: 'ko+f3', p: 72, s: 165, a: 160 },
  kaede: { v: 'ko+m5', p: 38, s: 135, a: 150 }, narration: { v: 'ko+f1', p: 42, s: 140, a: 150 },
};
export interface VoiceInfo { speaker: string; text: string; durationSec: number; frames: number; cues: { f: number; shape: MouthShape }[] }

function envelope(wavFile: string): number[] {
  const buf = readFileSync(wavFile); const rate = buf.readUInt32LE(24); const data = buf.subarray(44);
  const n = data.length / 2, per = Math.round(rate / 24), out: number[] = [];
  for (let i = 0; i + per <= n; i += per) { let s = 0; for (let k = 0; k < per; k++) { const v = data.readInt16LE((i + k) * 2); s += v * v; } out.push(Math.sqrt(s / per)); }
  return out;
}
export function cuesFromAudio(env: number[], text: string): { f: number; shape: MouthShape }[] {
  const max = Math.max(...env, 1); const vow = textMouthCues(text).filter((c) => !['closed', 'small'].includes(c.shape));
  const voiced = env.map((e) => e / max); const cues: { f: number; shape: MouthShape }[] = []; let last: MouthShape | null = null, vi = 0, prevOpen = false;
  const total = Math.max(1, voiced.filter((v) => v > 0.12).length);
  let seen = 0;
  voiced.forEach((v, f) => {
    let shape: MouthShape = 'closed';
    if (v > 0.12) { const open = true; if (!prevOpen) vi = Math.min(vow.length - 1, Math.floor((seen / total) * vow.length)); seen++; shape = v > 0.45 ? (vow[vi % Math.max(1, vow.length)]?.shape ?? 'a') : 'small'; prevOpen = open; } else prevOpen = false;
    if (shape !== last) { cues.push({ f, shape }); last = shape; }
  });
  if (last !== 'closed') cues.push({ f: voiced.length, shape: 'closed' });
  return cues;
}

export function generateVoices(force = false) {
  const check = spawnSync('espeak-ng', ['--version']); if (check.status !== 0) { console.log('espeak-ng not installed — voices stay MISSING_VOICE'); return; }
  mkdirSync('public/voices', { recursive: true });
  const shots = loadShots(); const analysis: Record<string, VoiceInfo> = {}; const manifest: Record<string, unknown> = {};
  for (const s of shots) s.dialogue.forEach((d, i) => {
    const id = dialogueId(s, i), file = `public/voices/${id}.wav`, vp = VOICES[d.speaker] ?? VOICES.narration;
    if (force || !existsSync(file)) execFileSync('espeak-ng', ['-v', vp.v, '-p', String(vp.p), '-s', String(vp.s), '-a', String(vp.a), '-w', file, d.text]);
    const env = envelope(file); const dur = env.length / 24;
    analysis[`${d.speaker}|${d.text}`] = { speaker: d.speaker, text: d.text, durationSec: +dur.toFixed(3), frames: Math.ceil(dur * 24), cues: cuesFromAudio(env, d.text) };
    manifest[id] = { shotId: s.shotId, speaker: d.speaker, text: d.text, engine: 'espeak-ng 1.51 (synthetic TTS placeholder)', voice: vp, durationSec: +dur.toFixed(3) };
  });
  writeJsonAtomic('episode/EP01/audio/voice_analysis.json', analysis);
  writeJsonAtomic('public/voices/manifest.json', { synthetic: true, note: 'SYNTHETIC espeak-ng TTS placeholders — not performances; replace per dialogueId', voices: manifest });
  writeFileSync('public/voices/PLACEHOLDER.md', '# Synthetic placeholder voices\nGenerated by `npm run production:voices` with espeak-ng. They are robotic stand-ins, not a voice performance, and no real person\'s voice is imitated. Replace any file with a real recording of the same name.\n');
  console.log(`voices: ${Object.keys(manifest).length} lines synthesised → public/voices/ ; analysis → episode/EP01/audio/voice_analysis.json`);
}
if (process.argv[1]?.endsWith('voices.ts')) generateVoices(process.argv.includes('--force'));
